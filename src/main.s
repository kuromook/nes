; =============================================================
; NES Hello World (ca65 / NROM-256, mapper 0)
;   起動して背景を 1 色で塗りつぶす最小サンプル。
;   ツールチェーン (ca65/ld65) とエミュレータの動作確認用。
; =============================================================

; ---- PPU / APU レジスタ ----
PPUCTRL   = $2000
PPUMASK   = $2001
PPUSTATUS = $2002
PPUADDR   = $2006
PPUDATA   = $2007

; -------------------------------------------------------------
; iNES ヘッダ (16 byte)
; -------------------------------------------------------------
.segment "HEADER"
    .byte "NES", $1A   ; マジックナンバー
    .byte 2            ; PRG-ROM 2 * 16KB = 32KB
    .byte 1            ; CHR-ROM 1 * 8KB
    .byte $00          ; flags6  : mapper 0, 横スクロールミラー
    .byte $00          ; flags7
    .byte $00,$00,$00,$00,$00,$00,$00,$00

; -------------------------------------------------------------
; リセット処理
; -------------------------------------------------------------
.segment "CODE"
.proc reset
    sei                ; 割り込み禁止
    cld                ; 10進モード解除
    ldx #$40
    stx $4017          ; APU フレーム IRQ 無効
    ldx #$ff
    txs                ; スタックポインタ初期化
    inx                ; X = 0
    stx PPUCTRL        ; NMI 無効
    stx PPUMASK        ; 描画オフ
    stx $4010          ; DMC IRQ 無効

    ; 1回目の vblank を待つ
:   bit PPUSTATUS
    bpl :-

    ; RAM クリア
    txa
clear_ram:
    sta $0000, x
    sta $0100, x
    sta $0200, x
    sta $0300, x
    sta $0400, x
    sta $0500, x
    sta $0600, x
    sta $0700, x
    inx
    bne clear_ram

    ; 2回目の vblank を待つ (PPU 安定化)
:   bit PPUSTATUS
    bpl :-

    ; パレット書き込み ($3F00-)
    bit PPUSTATUS      ; アドレスラッチをリセット
    lda #$3f
    sta PPUADDR
    lda #$00
    sta PPUADDR
    ldx #0
load_palette:
    lda palette, x
    sta PPUDATA
    inx
    cpx #32
    bne load_palette

    ; スクロール位置を 0 に
    lda #$00
    sta PPUADDR
    sta PPUADDR

    ; 描画オン + NMI 有効
    lda #%10000000     ; NMI 有効
    sta PPUCTRL
    lda #%00001110     ; 背景表示 ON
    sta PPUMASK

forever:
    jmp forever
.endproc

; -------------------------------------------------------------
; NMI (毎フレーム vblank で発生)
; -------------------------------------------------------------
.proc nmi
    rti
.endproc

; -------------------------------------------------------------
; パレットデータ
;   背景色 $21 = 明るい青。確認しやすいよう全体を青系に。
; -------------------------------------------------------------
.segment "RODATA"
palette:
    ; 背景パレット
    .byte $21,$10,$30,$0f,  $21,$06,$16,$0f
    .byte $21,$09,$19,$0f,  $21,$01,$11,$0f
    ; スプライトパレット
    .byte $21,$10,$30,$0f,  $21,$06,$16,$0f
    .byte $21,$09,$19,$0f,  $21,$01,$11,$0f

; -------------------------------------------------------------
; 割り込みベクタ
; -------------------------------------------------------------
.segment "VECTORS"
    .word nmi          ; $FFFA: NMI
    .word reset        ; $FFFC: RESET
    .word 0            ; $FFFE: IRQ/BRK

; -------------------------------------------------------------
; CHR-ROM (8KB) — 今は空 (タイルは全て 0)
; -------------------------------------------------------------
.segment "CHARS"
    .res 8192, $00
